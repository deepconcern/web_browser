#!/usr/bin/env python3
"""Generates src/entities.rs from WHATWG's entities.json.

Usage: python3 -I tools/gen_entities.py path/to/entities.json > src/entities.rs

entities.json is published with the HTML Living Standard at
https://html.spec.whatwg.org/entities.json (HTML §13.5, "Named character
references"). The WHATWG HTML standard is licensed under CC BY 4.0.
"""
import json
import sys


def rust_str(s):
    out = []
    for ch in s:
        cp = ord(ch)
        if 0x20 <= cp < 0x7F and ch not in '"\\':
            out.append(ch)
        else:
            out.append('\\u{%x}' % cp)
    return '"' + ''.join(out) + '"'


def main():
    with open(sys.argv[1], encoding='utf-8') as f:
        table = json.load(f)
    entries = sorted((name[1:], value['characters']) for name, value in table.items())
    longest = max(len(name) for name, _ in entries)
    print('//! Named character references (HTML §13.5).')
    print('//!')
    print("//! Generated by `tools/gen_entities.py` from WHATWG's `entities.json`")
    print('//! (<https://html.spec.whatwg.org/entities.json>, part of the HTML Living')
    print('//! Standard, CC BY 4.0). Do not edit by hand.')
    print()
    print('/// The length in characters of the longest name, including any `;`.')
    print('pub(crate) const LONGEST_NAME: usize = %d;' % longest)
    print()
    print('/// Every name (without the leading `&`) and its replacement characters,')
    print('/// sorted by name for binary search.')
    print('pub(crate) static ENTITIES: &[(&str, &str)] = &[')
    for name, value in entries:
        print('    (%s, %s),' % (rust_str(name), rust_str(value)))
    print('];')


main()
