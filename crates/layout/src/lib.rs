/// Resources layout needs from its embedder. Every method has a default,
/// so `NoHost` style implementations stay short.
pub trait LayoutHost {
    /// The natural size, in CSS px, of the image shown by `node` (an
    /// `<img>` or `<input type=image>`), if it has loaded. `None` lays the
    /// image out from its specified size only (0×0 when it has none).
    fn image_size(&self, node: NodeId) -> Option<Size> {
        let _ = node;
        None
    }

    /// The natural size of the image at the absolute `url` (for
    /// `list-style-image` and `content: url()`), if loaded.
    fn url_image_size(&self, url: &str) -> Option<Size> {
        let _ = url;
        None
    }

    /// The scroll offset of the scroll container generated by `node`
    /// (positive values scroll the content up and to the left). Layout
    /// clamps it to the scrollable range. The viewport's own scroll
    /// position is not applied by layout.
    fn scroll_offset(&self, node: NodeId) -> Point {
        let _ = node;
        Point::ZERO
    }
}

/// A [`LayoutHost`] with no images loaded and nothing scrolled.
#[derive(Clone, Copy, Debug, Default)]
pub struct NoHost;

impl LayoutHost for NoHost {}

/// Per-layout inputs.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct LayoutOptions {
    /// The viewport size in CSS px: the initial containing block (CSS 2.2
    /// §10.1).
    pub viewport: Size,
}

impl Default for LayoutOptions {
    fn default() -> Self {
        LayoutOptions {
            viewport: Size::new(800.0, 600.0),
        }
    }
}

/// Builds the box tree for `doc` styled as `styles`.
pub fn build_box_tree(doc: &Document, styles: &StyledDocument) -> BoxTree {
    box_tree::build_box_tree(doc, styles)
}

/// Lays out `tree` in the viewport given by `options`.
pub fn layout_box_tree(
    tree: &BoxTree,
    fonts: &FontContext,
    host: &dyn LayoutHost,
    options: &LayoutOptions,
) -> FragmentTree {
    context::layout_tree(tree, fonts, host, options)
}

/// Builds the box tree of `doc` and lays it out.
pub fn layout_document(
    doc: &Document,
    styles: &StyledDocument,
    fonts: &FontContext,
    host: &dyn LayoutHost,
    options: &LayoutOptions,
) -> FragmentTree {
    let tree = build_box_tree(doc, styles);
    layout_box_tree(&tree, fonts, host, options)
}
