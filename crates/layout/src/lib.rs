//! Box generation and layout.
//!
//! # Overview
//!
//! 1. [`build_box_tree`] turns a [`Document`] and its [`StyledDocument`]
//!    into a [`BoxTree`] (CSS Display 3, CSS 2.2 §9.2): `display: none`
//!    and `contents`, anonymous block and inline boxes, inline boxes split
//!    around blocks, `::before`/`::after` content and `::marker` boxes,
//!    replaced elements and form controls.
//! 2. [`layout_box_tree`] lays the tree out for a viewport and returns a
//!    [`FragmentTree`]: every fragment with absolute border, padding and
//!    content rectangles in CSS px, its DOM node, its computed style, and
//!    stacking information for paint. [`FragmentTree::hit_test`] maps a
//!    point back to a node.
//!
//! [`layout_document`] does both.
//!
//! The caller supplies a [`wb_text::FontContext`] for shaping and a
//! [`LayoutHost`] for resources layout does not own: decoded image sizes
//! and scroll offsets.
//!
//! # Spec coverage (M1 core)
//!
//! - Block formatting contexts with margin collapsing (CSS 2.2 §8.3.1),
//!   widths and heights (§10.3, §10.6), `min-`/`max-` sizes (§10.4,
//!   §10.7), `box-sizing`.
//! - Inline formatting contexts (CSS 2.2 §9.4.2, §10.8, CSS Inline 3):
//!   white-space processing and `text-transform` (CSS Text 3 §2, §4),
//!   line breaking with UAX #14 through `wb-text`, `overflow-wrap`,
//!   `text-align` (with `justify`), `text-indent`, `vertical-align`,
//!   `letter-spacing`/`word-spacing`, inline-blocks and inline replaced
//!   elements.
//! - Intrinsic sizes (CSS Sizing 3 §4–§5) for shrink-to-fit widths.
//! - Replaced elements (CSS 2.2 §10.3.2, §10.6.2), form controls with UA
//!   default sizes.
//! - List markers (CSS Lists 3), relative positioning (CSS 2.2 §9.4.3),
//!   overflow clipping and scroll offsets (CSS Overflow 3).
//!
//! - Floats and `clear` (CSS 2.2 §9.5): placement, line boxes shortened
//!   beside floats, clearance, BFC roots avoiding floats and containing
//!   them (§10.6.7).
//! - Absolute and fixed positioning (CSS 2.2 §9.6, §10.3.7, §10.6.4, CSS
//!   Position 3) against the nearest positioned ancestor or the viewport;
//!   `sticky` is laid out as `relative`. Fixed boxes scroll with the
//!   document in M1.
//! - Flex layout (CSS Flexbox 1 §9).
//!
//! Tables are laid out as block containers until their module lands (see
//! the `M1 follow-up` notes in `formatting/`). Grid and multi-column fall
//! back to block layout by design in M1.
